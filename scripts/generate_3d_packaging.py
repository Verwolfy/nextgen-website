    # Turn front facing via cylinder alignment from vertical to outward.
    p['tap-body'].apply_transform(trimesh.transformations.rotation_matrix(math.pi/2,[1,0,0],point=[0,0,.18]))
    p['tap-body'].apply_translation([0,-.66,0])
