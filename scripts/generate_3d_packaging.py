MODELS={
 'sac-25kg':('sac',bag),
 'seau-20kg':('seau',bucket),
 'bidon-20l':('bidon',jerrycan),
 'fut-200l':('fut',barrel),
 'ibc-1000l':('ibc',ibc),
}


def generate():
    manifest=[]
    for filename,(kind,factory) in MODELS.items():
        meshes=factory()
        scene=trimesh.Scene()
        for name,mesh in meshes.items():
            scene.add_geometry(mesh,geom_name=name,node_name=name)
        raw=scene.export(file_type='glb')
        out=OUT_DIR/(filename+'.glb')
        out.write_bytes(raw)
        if raw[:4]!=b'glTF' or len(raw)>3*1024*1024:
            raise ValueError(f'Invalid or overlarge GLB: {out}')
        imported=trimesh.load(out,force='scene')
        if not imported.geometry or not all(np.isfinite(g.vertices).all() for g in imported.geometry.values()):
            raise ValueError(f'Invalid geometry {filename}')
        is_textured=sum(isinstance(g.visual,TextureVisuals) for g in imported.geometry.values())
        if is_textured!=1:raise ValueError(f'Expected original-label texture: {filename}; {is_textured}')
        manifest.append({'code':filename,'type':kind,'source_label':f'etiquette-{kind}.png',
                         'source_logo':'Logo1.jpg (included in label unchanged)',
                         'url':f'/models-demo/{filename}.glb','filesize_bytes':len(raw),
                         'vertices':sum(len(g.vertices) for g in imported.geometry.values()),
                         'status':'SIMULATION – BROUILLON NON VALIDÉ'})
    (ROOT/'supports/3d/manifest.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n')
    return manifest

if __name__=='__main__':
    for item in generate():print(f"{item['code']}: {item['filesize_bytes']} bytes, {item['vertices']} vertices")
