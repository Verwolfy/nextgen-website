#!/usr/bin/env python3
"""Generate five 3D draft packaging GLBs from existing NextGen label artwork.

These are illustrative packaging meshes, not manufacturing specifications or
validated product claims. Original NG logo remains embedded in the exact source
label artwork; never recreated or redrawn here. Safe to run without credentials.
"""
from __future__ import annotations

import json
import math
from pathlib import Path

import numpy as np
import trimesh
from PIL import Image
from trimesh.visual.material import SimpleMaterial
from trimesh.visual.texture import TextureVisuals

ROOT = Path(__file__).resolve().parents[1]
LABEL_DIR = ROOT / 'supports/etiquettes/apercus'
OUT_DIR = ROOT / 'supports/3d/glb'
OUT_DIR.mkdir(parents=True, exist_ok=True)

NAVY = '#112851'
GREEN = '#009762'
WHITE = '#f6f7f7'
METAL = '#9ea8ad'
SAND = '#c4bba9'


def rgba(h: str, alpha: int = 255):
    return tuple(bytes.fromhex(h.replace('#',''))) + (alpha,)


def solid(mesh: trimesh.Trimesh, color: str, alpha=255):
    mesh.visual.vertex_colors = rgba(color,alpha)
    return mesh


def box(extents, position, color: str):
    mesh = trimesh.creation.box(extents=extents)
    mesh.apply_translation(position)
    return solid(mesh, color)


def tube_between(a, b, radius, color=METAL, sections=12):
    return solid(trimesh.creation.cylinder(radius=radius, segment=np.array([a,b]), sections=sections),color)


def ring(major_radius, minor_radius, z, color, sides=40, tube_sides=6):
    vertices=[]
    faces=[]
    for i in range(sides):
        theta=2*math.pi*i/sides
        for j in range(tube_sides):
            phi=2*math.pi*j/tube_sides
            vertices.append(((major_radius+minor_radius*math.cos(phi))*math.cos(theta),
                             (major_radius+minor_radius*math.cos(phi))*math.sin(theta),
                             z+minor_radius*math.sin(phi)))
    for i in range(sides):
        for j in range(tube_sides):
            a=i*tube_sides+j
            b=((i+1)%sides)*tube_sides+j
            c=((i+1)%sides)*tube_sides+(j+1)%tube_sides
            d=i*tube_sides+(j+1)%tube_sides
            faces.extend([[a,b,c],[a,c,d]])
    return solid(trimesh.Trimesh(vertices=vertices, faces=faces, process=False),color)


def cylinder(radius, height, center_z, color, sections=48):
    mesh=trimesh.creation.cylinder(radius=radius, height=height, sections=sections)
    mesh.apply_translation([0,0,center_z])
    return solid(mesh,color)


def tapered_cylinder(r_bottom, r_top, height, center_z, color, sections=48):
    # Surface mesh plus two end faces: flat normals generated by trimesh.
    verts=[]
    for z,r in [(-height/2,r_bottom),(height/2,r_top)]:
        verts.extend([(r*math.sin(t*2*math.pi/sections),-r*math.cos(t*2*math.pi/sections),z+center_z) for t in range(sections)])
    verts.extend([(0,0,center_z-height/2),(0,0,center_z+height/2)])
    faces=[]
    for i in range(sections):
        j=(i+1)%sections
        faces.extend([[i,j,sections+j],[i,sections+j,sections+i],
                      [2*sections,j,i], [2*sections+1,sections+i,sections+j]])
    return solid(trimesh.Trimesh(vertices=verts,faces=faces,process=False),color)


def label_image(kind: str):
    im=Image.open(LABEL_DIR / f'etiquette-{kind}.png').convert('RGB')
    im.thumbnail((900,600),Image.Resampling.LANCZOS)
    return im


def add_label_plane(parts, name, image, width, height, yfront, zmid):
    v=np.array([[-width/2,yfront,zmid-height/2],
                [width/2,yfront,zmid-height/2],
                [width/2,yfront,zmid+height/2],
                [-width/2,yfront,zmid+height/2]],dtype=float)
    mesh=trimesh.Trimesh(vertices=v,faces=[[0,1,2],[0,2,3]],process=False)
    # Face winding provides visible front through glTF double-sided flag.
    mesh.visual=TextureVisuals(uv=np.array([[0,0],[1,0],[1,1],[0,1]]),
                              material=SimpleMaterial(image=image, diffuse=[255,255,255,255],ambient=[255,255,255,255]))
    parts[name]=mesh


def add_label_curve(parts,name,image,radius,angle,zmid,height,sections=30):
    vertices=[];uv=[]
    for i in range(sections+1):
        t=2*i/sections-1
        a=t*angle
        vertices.append([radius*math.sin(a),-radius*math.cos(a),zmid-height/2]);uv.append([i/sections,0])
        vertices.append([radius*math.sin(a),-radius*math.cos(a),zmid+height/2]);uv.append([i/sections,1])
    faces=[]
    for i in range(sections):
        lo=2*i;faces.extend([[lo,lo+2,lo+1],[lo+1,lo+2,lo+3]])
    mesh=trimesh.Trimesh(vertices=vertices,faces=faces,process=False)
    mesh.visual=TextureVisuals(uv=np.array(uv),material=SimpleMaterial(image=image, diffuse=[255,255,255,255],ambient=[255,255,255,255]))
    parts[name]=mesh


def add_round_handle(parts,label,x_min,x_max,z1,z2,y,metal=METAL):
    points=[[x_min,y,z1],[x_min,y,z2],[x_min+.07,y,z2+.055],[x_max-.07,y,z2+.055],[x_max,y,z2],[x_max,y,z1]]
    for i in range(len(points)-1):
        parts[f'{label}-{i}']=tube_between(points[i],points[i+1],.028,metal,10)


def bag():
    label=label_image('sac');p={}
    # Kraft laminated 25 kg multiwall sack. Shoulders slightly pinched, soft draft shape.
    coords=[(-.55,-.12,.07),(.55,-.12,.07),(.55,.12,.07),(-.55,.12,.07),
            (-.58,-.14,.62),(.58,-.14,.62),(.58,.14,.62),(-.58,.14,.62),
            (-.52,-.10,1.15),(.52,-.10,1.15),(.52,.10,1.15),(-.52,.10,1.15)]
    p['bag-body']=solid(trimesh.convex.convex_hull(np.array(coords)), '#e8e3d7')
    p['bottom-seam']=box((1.12,.255,.025),(0,0,.083),NAVY)
    p['folded-top']=box((1.035,.205,.05),(0,0,1.16),'#d9d7cf')
    p['top-edge']=box((1.035,.208,.023),(0,0,1.195),GREEN)
    add_label_plane(p,'nextgen-original-label',label,1.02,.60,-.148,.65)
    return p


